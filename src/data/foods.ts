// The Filipino food database (Phase 1: local records). One record per dish —
// a dish that belongs to several categories lists them all instead of being duplicated.
// Prices are ESTIMATED cost of one serving in PHP (carinderia / home-cooked level).
import type { CategoryId, CookingMethod, MainIngredient, Region, Taste } from "./food-filters";

export interface FoodRecord {
  id: string;
  name: string;
  /** Other names people search for, e.g. "Batchoy" for La Paz Batchoy */
  aliases?: string[];
  description: string;
  categories: CategoryId[];
  region: Region;
  mainIngredients: MainIngredient[];
  /** Key ingredients shown on the details page and used by search */
  ingredients: string[];
  methods: CookingMethod[];
  tastes: Taste[];
  /** Estimated price per serving, PHP */
  price: number;
  featured?: boolean;
  popularity: number;
}

type Cats = CategoryId[];
type Ings = MainIngredient[];
type Meths = CookingMethod[];
type Tastes = Taste[];

function food(
  id: string,
  name: string,
  categories: Cats,
  region: Region,
  mainIngredients: Ings,
  methods: Meths,
  tastes: Tastes,
  price: number,
  ingredients: string,
  description: string,
  extra: { aliases?: string[]; featured?: boolean; popularity?: number } = {},
): FoodRecord {
  return {
    id, name, categories, region, mainIngredients, methods, tastes, price, description,
    ingredients: ingredients.split(",").map((s) => s.trim()),
    aliases: extra.aliases,
    featured: extra.featured,
    popularity: extra.popularity ?? 60,
  };
}

